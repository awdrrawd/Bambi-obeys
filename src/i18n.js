const DICTIONARIES = { en: EN, "zh-CN": ZH_CN };

function detectLocale() {
    const gameLanguage = globalThis.TranslationLanguage;
    const candidate = String(gameLanguage || globalThis.navigator?.language || "en").toLowerCase();
    return candidate.startsWith("zh") || candidate === "cn" ? "zh-CN" : "en";
}

export function createI18n(initialLocale = "auto") {
    let requestedLocale = initialLocale;
    const resolveLocale = () => requestedLocale === "auto" ? detectLocale() : requestedLocale;

    return {
        get locale() { return requestedLocale; },
        get resolvedLocale() { return resolveLocale(); },
        setLocale(locale) {
            requestedLocale = DICTIONARIES[locale] ? locale : "auto";
            return requestedLocale;
        },
        t(key, params = {}) {
            const dictionary = DICTIONARIES[resolveLocale()] || EN;
            const template = dictionary[key] ?? EN[key] ?? key;
            return template.replace(/\{(\w+)\}/g, (_, name) =>
                Object.prototype.hasOwnProperty.call(params, name) ? String(params[name]) : `{${name}}`
            );
        }
    };
}
